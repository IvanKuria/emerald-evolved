"""Writes src/data/hybrid_sprites.h (ramps, owner ramp maps, baked part layers) from hybrid_table.py.
usage (from the repo root): python3 tools/hybrid/bake.py      (needs Pillow)"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hybrid_table as T
import hybrid_lib as L

OUT = L.ROOT / 'src' / 'data' / 'hybrid_sprites.h'
VIEW_C = {'f1': 'HYBRID_VIEW_FRONT_1', 'f2': 'HYBRID_VIEW_FRONT_2', 'back': 'HYBRID_VIEW_BACK'}


def sp_c(sp): return 'SPECIES_' + sp.upper()
def rgb(c): return f'0x{c[0] | (c[1] << 5) | (c[2] << 10):04X}'   # RGB555 (RGB() is not a constant expression here)


def main():
    o = ['// GENERATED by tools/hybrid/bake.py from tools/hybrid/hybrid_table.py - do not edit by hand.',
         "// Cross-breed hybrid sprites: body ramps, the owner's ramp maps and real body parts baked from the ROM's own art.",
         '']
    o.append('static const struct HybridRamp sHybridRamps[] =\n{')
    nr = 0
    for sp in T.RAMP_SPECIES:
        r = L.ramp(sp)
        if r:
            o.append(f'    {{{sp_c(sp)}, {len(r)}, {{{", ".join(map(str, r))}}}}},'); nr += 1
    o.append('};\n')

    o.append('static const struct HybridRampMap sHybridRampMaps[] =\n{')
    for (body, colour), m in T.RAMP_MAPS.items():
        pairs = sorted(m.items())
        o.append(f'    {{{sp_c(body)}, {sp_c(colour)}, {len(pairs)}, {{{", ".join(str(b) for b, _ in pairs)}}}, '
                 f'{{{", ".join(str(c) for _, c in pairs)}}}}},')
    o.append('};\n')

    rows = []; n = 0
    for (body, part) in T.PLACEMENTS:
        for (view, behind, x, y, w, h, pix, cols) in L.layers(body, part):
            o.append(f'static const u16 sHybridLayerColours{n}[] = {{{", ".join(rgb(c) for c in cols)}}};')
            flat = [v for row in pix for v in row]
            txt = ',\n    '.join(', '.join(map(str, flat[i:i + 32])) for i in range(0, len(flat), 32))
            o.append(f'static const u8 sHybridLayerPixels{n}[] =\n{{\n    {txt}\n}};')
            rows.append(f'    {{{sp_c(body)}, {sp_c(part)}, {VIEW_C[view]}, {"TRUE" if behind else "FALSE"}, '
                        f'{x}, {y}, {w}, {h}, {len(cols)}, sHybridLayerColours{n}, sHybridLayerPixels{n}}},')
            n += 1
    o.append('\nstatic const struct HybridLayer sHybridLayers[] =\n{')
    o += rows
    o.append('};\n')
    OUT.write_text('\n'.join(o))
    print(f'{OUT.relative_to(L.ROOT)}: {nr} ramps, {len(T.RAMP_MAPS)} ramp maps, {n} layers')


if __name__ == '__main__':
    main()
