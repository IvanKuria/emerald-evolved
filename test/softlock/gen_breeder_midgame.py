#!/usr/bin/env python3
"""Generate include/breeder_midgame.h: the 'arrived in Mauville' story state for SL_TEST builds.

Base = upstream's own Debug_CheatStart intro state (data/scripts/debug.inc, first block) + the story vars/flags the
pre-Mauville maps set (Littleroot .. Route 110), hand-checked values below. FLAG_HIDE_* flags that the pre-Mauville
scripts only ever set (or only ever clear) are applied; flags they both set and clear keep their new-game value.
"""
import re, glob, os, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PRE = ['LittlerootTown', 'Route101', 'OldaleTown', 'Route103', 'Route102', 'PetalburgCity', 'Route104', 'PetalburgWoods',
       'RustboroCity', 'Route116', 'RusturfTunnel', 'Route105', 'Route106', 'Route107', 'Route108', 'Route109',
       'DewfordTown', 'GraniteCave', 'SlateportCity', 'Route110']
VARS = dict(VAR_LITTLEROOT_INTRO_STATE=7, VAR_LITTLEROOT_TOWN_STATE=4, VAR_LITTLEROOT_RIVAL_STATE=4,
            VAR_LITTLEROOT_HOUSES_STATE_BRENDAN=2, VAR_LITTLEROOT_HOUSES_STATE_MAY=2, VAR_BIRCH_LAB_STATE=5,
            VAR_ROUTE101_STATE=3, VAR_OLDALE_RIVAL_STATE=2, VAR_OLDALE_TOWN_STATE=1, VAR_PETALBURG_CITY_STATE=3,
            VAR_PETALBURG_GYM_STATE=1, VAR_PETALBURG_WOODS_STATE=1, VAR_RUSTBORO_CITY_STATE=8, VAR_RUSTURF_TUNNEL_STATE=3,
            VAR_ROUTE104_STATE=2, VAR_ROUTE116_STATE=2, VAR_BRINEY_HOUSE_STATE=1, VAR_BRINEY_LOCATION=3,
            VAR_BOARD_BRINEY_BOAT_STATE=2, VAR_DEVON_CORP_3F_STATE=1, VAR_ROUTE110_STATE=1, VAR_SLATEPORT_CITY_STATE=2,
            VAR_SLATEPORT_OUTSIDE_MUSEUM_STATE=2, VAR_SLATEPORT_FAN_CLUB_STATE=1, VAR_SCOTT_STATE=1,
            VAR_SCOTT_PETALBURG_ENCOUNTER=1, VAR_CABLE_CLUB_TUTORIAL_STATE=2, VAR_REGISTER_BIRCH_STATE=2)
FLAGS = '''FLAG_SYS_POKEMON_GET FLAG_RESCUED_BIRCH FLAG_HIDE_ROUTE_101_BIRCH_ZIGZAGOON_BATTLE FLAG_ADVENTURE_STARTED
FLAG_HIDE_ROUTE_101_BIRCH_STARTERS_BAG FLAG_SYS_POKEDEX_GET FLAG_RECEIVED_POKEDEX_FROM_BIRCH FLAG_RECEIVED_RUNNING_SHOES
FLAG_SYS_B_DASH FLAG_BADGE01_GET FLAG_BADGE02_GET FLAG_VISITED_LITTLEROOT_TOWN FLAG_VISITED_OLDALE_TOWN
FLAG_VISITED_PETALBURG_CITY FLAG_VISITED_RUSTBORO_CITY FLAG_VISITED_DEWFORD_TOWN FLAG_VISITED_SLATEPORT_CITY
FLAG_DEFEATED_RUSTBORO_GYM FLAG_DEFEATED_DEWFORD_GYM FLAG_DEFEATED_RIVAL_ROUTE103 FLAG_DEFEATED_RIVAL_RUSTBORO
FLAG_RECEIVED_POKENAV FLAG_SYS_POKENAV_GET FLAG_HAS_MATCH_CALL FLAG_ADDED_MATCH_CALL_TO_POKENAV FLAG_RECEIVED_HM_CUT
FLAG_RECEIVED_HM_FLASH FLAG_RECOVERED_DEVON_GOODS FLAG_RETURNED_DEVON_GOODS FLAG_DELIVERED_STEVEN_LETTER
FLAG_DELIVERED_DEVON_GOODS FLAG_MET_RIVAL_MOM FLAG_MET_RIVAL_RUSTBORO FLAG_MET_DEVON_EMPLOYEE
FLAG_INTERACTED_WITH_DEVON_EMPLOYEE_GOODS_STOLEN FLAG_MET_SCOTT_RUSTBORO FLAG_MET_SCOTT_AFTER_OBTAINING_STONE_BADGE
FLAG_MR_BRINEY_SAILING_INTRO FLAG_EVIL_TEAM_ESCAPED_STERN_SPOKE FLAG_MET_TEAM_AQUA_HARBOR FLAG_BIRCH_AIDE_MET
FLAG_RECEIVED_TM_ROCK_TOMB FLAG_RECEIVED_TM_BULK_UP FLAG_LANDMARK_MR_BRINEY_HOUSE FLAG_LANDMARK_FLOWER_SHOP
FLAG_LANDMARK_SEASHORE_HOUSE FLAG_LANDMARK_TUNNELERS_REST_HOUSE FLAG_RIVAL_LEFT_FOR_ROUTE103 FLAG_HIDE_ROUTE_116_MR_BRINEY
FLAG_RECEIVED_POTION_OLDALE FLAG_MET_PRETTY_PETAL_SHOP_OWNER'''.split()
CLEAR = ['FLAG_HIDE_LITTLEROOT_TOWN_BIRCHS_LAB_BIRCH']
hs, hc = collections.Counter(), collections.Counter()
for d in sorted(glob.glob(os.path.join(ROOT, 'data/maps/*'))):
    n = os.path.basename(d)
    if not any(n == p or n.startswith(p + '_') for p in PRE) or any(k in n for k in ('TrickHouse', 'BattleTent', 'Frlg')):
        continue
    f = os.path.join(d, 'scripts.inc')
    if os.path.exists(f):
        for op, fl in re.findall(r'^\s*(setflag|clearflag) (FLAG_HIDE_\w+)', open(f).read(), re.M):
            (hs if op == 'setflag' else hc)[fl] += 1
hide_set = sorted(f for f in hs if f not in hc)
hide_clr = sorted(f for f in hc if f not in hs)
with open(os.path.join(ROOT, 'include/breeder_midgame.h'), 'w') as o:
    o.write('// Generated by test/softlock/gen_midgame.py. Breeder start: the "arrived in Mauville" story state (same set the softlock sweep tested).\n')
    o.write('static const u16 sBreederMidFlagsSet[] = {\n' + ''.join(f'    {f},\n' for f in FLAGS + hide_set) + '};\n')
    o.write('static const u16 sBreederMidFlagsClear[] = {\n' + ''.join(f'    {f},\n' for f in CLEAR + hide_clr) + '};\n')
    o.write('static const u16 sBreederMidVars[][2] = {\n' + ''.join(f'    {{{k}, {v}}},\n' for k, v in VARS.items()) + '};\n')
print(len(FLAGS), len(hide_set), len(hide_clr), len(VARS))
